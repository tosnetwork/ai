// RoomVector is one room carriage vector. A single object has Wire; a split
// object or a reassembly sequence has Frames, offered in order to a
// reassembler cut at PartBytes (0 for the production cut). A frame with no
// Wire is generated by Recipe, and only its digest and length are committed.
type RoomVector struct {
	Name      string            `json:"name"`
	Wire      string            `json:"wire_hex,omitempty"`
	SHA256    string            `json:"sha256,omitempty"`
	Bytes     int               `json:"bytes,omitempty"`
	Error     string            `json:"error,omitempty"`
	PartBytes int               `json:"part_bytes,omitempty"`
	Recipe    string            `json:"recipe,omitempty"`
	Members   []string          `json:"members,omitempty"`
	Frames    []RoomFrameVector `json:"frames,omitempty"`
}

// RoomFrameVector is one kind-3 frame from a sender, and the reassembler's
// fixed error for it, or empty when it is accepted.
type RoomFrameVector struct {
	Sender string `json:"sender"`
	Wire   string `json:"wire_hex,omitempty"`
	SHA256 string `json:"sha256"`
	Bytes  int    `json:"bytes"`
	Error  string `json:"error,omitempty"`
}

const (
	vectorRoom      = "room_" + "7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a7a"
	maximalRecipe   = "Welcome, room epoch 7, MLS epoch 9; header: members agent_<64-hex of 1..32>, network ID 128 x 'n', genesis hashes 64 x 'a' and 64 x 'b', authority the first member with mep_<64 x 'e'>, issued 1,800,000,000, expires +3,600, signed by the vector Endpoint key; body 1,048,576 bytes, byte i = i mod 251; part 0 carries the vector evidence and no card"
	vectorPartBytes = relayframe.MinTestPartBytes
)

func vectorAgent(index int) string { return fmt.Sprintf("agent_%064x", index+1) }

func roomHeaderVector(t *testing.T, epoch uint64, members int, networkID string) *relayframe.RoomHeader {
	t.Helper()
	agents := make([]string, members)
	for index := range agents {
		agents[index] = vectorAgent(index)
	}
	digest, err := room.Digest(vectorRoom, epoch, agents)
	if err != nil {
		t.Fatal(err)
	}
	membership := room.Membership{RoomID: vectorRoom, Epoch: epoch, Members: agents, Digest: digest}
	base := delegation(t).Network
	network := &nativev1.NetworkDomain{NetworkId: base.NetworkId, GenesisRootHash: base.GenesisRootHash, GenesisFileHash: base.GenesisFileHash}
	if networkID != "" {
		network.NetworkId = networkID
	}
	authorization, err := room.SignMembershipAuthorization(room.MembershipAuthorization{Network: network, RoomID: vectorRoom,
		Epoch: epoch, MembershipDigest: digest, Authority: room.Authority{AgentID: agents[0], EndpointID: "mep_" + strings.Repeat("e", 64)},
		IssuedAtUnix: baseUnix, ExpiresAtUnix: baseUnix + 3600}, endpointKey())
	if err != nil {
		t.Fatal(err)
	}
	return &relayframe.RoomHeader{Membership: membership, Authorization: authorization}
}

func relayEvidenceVector(t *testing.T) []byte {
	t.Helper()
	for _, vector := range buildRelay(t) {
		if vector.Name == "relay-evidence" {
			raw, err := hex.DecodeString(vector.Wire)
			if err != nil {
				t.Fatal(err)
			}
			return raw
		}
	}
	t.Fatal("no relay evidence vector")
	return nil
}

type vectorSenders struct{ members map[string]bool }

func (s vectorSenders) MayHold(sender string) bool { return s.members[sender] }
func (s vectorSenders) MayHoldInRoom(sender, roomID string) bool {
	return s.members[sender] && roomID == vectorRoom
}

func TestRoomCarriageVectors(t *testing.T) {
	produced := buildRoom(t)
	path := filepath.Join("testdata", "relay-room-vectors.json")
	encoded, err := json.MarshalIndent(produced, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	encoded = append(encoded, '\n')
	if *update {
		if err := os.WriteFile(path, encoded, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read committed room vectors: %v (run with -update to create them)", err)
	}
	if !bytes.Equal(committed, encoded) {
		t.Fatal("the room carriage forms changed; this is a wire-format change. Re-run with -update and review the diff.")
	}
	for _, vector := range produced {
		if err := checkRoomVector(t, vector); err != nil {
			t.Fatalf("%s: %v", vector.Name, err)
		}
	}
}

// checkRoomVector decodes, or reassembles, a committed vector exactly as it
// says.
func checkRoomVector(t *testing.T, vector RoomVector) error {
	if len(vector.Frames) == 0 {
		raw, err := hex.DecodeString(vector.Wire)
		if err != nil {
			return err
		}
		// An over-bound object is committed by recipe: that many zero bytes.
		if vector.Wire == "" {
			raw = make([]byte, vector.Bytes)
		}
		if canon.Digest(raw) != vector.SHA256 || len(raw) != vector.Bytes {
			return fmt.Errorf("does not match its digest or length")
		}
		var decodeErr error
		switch {
		case strings.HasPrefix(vector.Name, "room-object"):
			_, decodeErr = relayframe.DecodeRoomObject(raw)
		case strings.HasPrefix(vector.Name, "room-roster"):
			_, decodeErr = relayframe.DecodeRoster(raw)
		case strings.HasPrefix(vector.Name, "room-ack"):
			_, decodeErr = relayframe.DecodeRoomAck(raw)
		case strings.HasPrefix(vector.Name, "room-aad"):
			decodeErr = nil
		default:
			return fmt.Errorf("unclassified room vector")
		}
		if (vector.Error == "") != (decodeErr == nil) || decodeErr != nil && decodeErr.Error() != vector.Error {
			return fmt.Errorf("decode error %v, vector says %q", decodeErr, vector.Error)
		}
		return nil
	}
	limits := relayframe.DefaultReassemblyLimits()
	limits.PartBytes = vector.PartBytes
	senders := vectorSenders{members: map[string]bool{}}
	for _, member := range vector.Members {
		senders.members[member] = true
	}
	reassembler, err := relayframe.NewReassembler(limits, senders)
	if err != nil {
		return err
	}
	var generated [][]byte
	if vector.Recipe != "" {
		generated, err = relayframe.SplitRoomObject(maximalObject(t), nil, relayEvidenceVector(t), 0)
		if err != nil {
			return err
		}
	}
	for index, frameVector := range vector.Frames {
		var raw []byte
		if frameVector.Wire != "" {
			raw, err = hex.DecodeString(frameVector.Wire)
			if err != nil {
				return err
			}
		} else {
			raw = generated[index]
		}
		if canon.Digest(raw) != frameVector.SHA256 || len(raw) != frameVector.Bytes {
			return fmt.Errorf("frame %d does not match its digest or length", index)
		}
		frame, err := relayframe.Decode(raw)
		if err != nil {
			return fmt.Errorf("frame %d: %v", index, err)
		}
		_, addErr := reassembler.Add(frameVector.Sender, frame, time.Unix(int64(baseUnix), 0))
		if (frameVector.Error == "") != (addErr == nil) || addErr != nil && addErr.Error() != frameVector.Error {
			return fmt.Errorf("frame %d: reassembly error %v, vector says %q", index, addErr, frameVector.Error)
		}
	}
	return nil
}

func maximalObject(t *testing.T) []byte {
	t.Helper()
	body := make([]byte, relayframe.MaxRoomBodyBytes)
	for index := range body {
		body[index] = byte(index % 251)
	}
	raw, err := relayframe.EncodeRoomObject(relayframe.RoomObject{Type: relayframe.RoomWelcome, RoomID: vectorRoom, RoomEpoch: 7, MLSEpoch: 9,
		Header: roomHeaderVector(t, 7, relayframe.MaxRoomMembers, strings.Repeat("n", 128)), Body: body})
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

func buildRoom(t *testing.T) []RoomVector {
	t.Helper()
	evidence := relayEvidenceVector(t)
	var vectors []RoomVector
	add := func(name string, raw []byte, expected error) {
		vector := RoomVector{Name: name, Wire: hex.EncodeToString(raw), SHA256: canon.Digest(raw), Bytes: len(raw)}
		if expected != nil {
			vector.Error = expected.Error()
		}
		vectors = append(vectors, vector)
	}
	object := func(value relayframe.RoomObject) []byte {
		raw, err := relayframe.EncodeRoomObject(value)
		if err != nil {
			t.Fatal(err)
		}
		return raw
	}
	header := roomHeaderVector(t, 2, 3, "")
	commit := object(relayframe.RoomObject{Type: relayframe.RoomCommit, RoomID: vectorRoom, RoomEpoch: 2, MLSEpoch: 4, Header: header, Body: []byte("mls commit")})
	add("room-object-commit", commit, nil)
	add("room-object-refresh-commit", object(relayframe.RoomObject{Type: relayframe.RoomCommit, RoomID: vectorRoom, RoomEpoch: 2, MLSEpoch: 5, Body: []byte("mls refresh")}), nil)
	welcome := object(relayframe.RoomObject{Type: relayframe.RoomWelcome, RoomID: vectorRoom, RoomEpoch: 2, MLSEpoch: 4, Header: header, Body: bytes.Repeat([]byte("w"), 3_000)})
	add("room-object-welcome", welcome, nil)
	add("room-object-application", object(relayframe.RoomObject{Type: relayframe.RoomApplication, RoomID: vectorRoom, RoomEpoch: 2, MLSEpoch: 4, Body: []byte("private message")}), nil)
	roster, err := relayframe.EncodeRoster([]relayframe.RosterEntry{
		{AgentID: vectorAgent(1), Card: []byte(`{"card":"member two"}`), Evidence: evidence},
		{AgentID: vectorAgent(2), Card: []byte(`{"card":"member three"}`), Evidence: evidence},
	})
	if err != nil {
		t.Fatal(err)
	}
	add("room-roster", roster, nil)
	add("room-object-roster", object(relayframe.RoomObject{Type: relayframe.RoomRoster, RoomID: vectorRoom, RoomEpoch: 2, MLSEpoch: 4, Header: header, Body: roster}), nil)
	// Malformed objects, each refused with the fixed error.
	refresh := object(relayframe.RoomObject{Type: relayframe.RoomCommit, RoomID: vectorRoom, RoomEpoch: 2, MLSEpoch: 5, Body: []byte("x")})
	headerless := append([]byte(nil), refresh...)
	headerless[len(canon.DomainRelayRoomObject)] = relayframe.RoomWelcome
	add("room-object-welcome-without-header", headerless, relayframe.ErrRoomObjectMalformed)
	add("room-object-trailing-byte", append(append([]byte(nil), commit...), 0), relayframe.ErrRoomObjectMalformed)
	add("room-object-over-bound", make([]byte, relayframe.MaxRoomObjectBytes+1), relayframe.ErrRoomObjectTooLarge)
	vectors[len(vectors)-1].Wire = ""
	vectors[len(vectors)-1].Recipe = fmt.Sprintf("%d zero bytes", relayframe.MaxRoomObjectBytes+1)
	// The room ack and AAD.
	ack, err := relayframe.SignRoomAck(relayframe.RoomAck{RoomID: vectorRoom, ObjectDigest: relayframe.ObjectDigest(commit),
		RecipientEndpointID: delegation(t).EndpointID, RecipientDeviceID: deviceOne, MLSEpoch: 4,
		EpochAuthenticator: bytes.Repeat([]byte{0xa7}, 32), Outcome: relayframe.OutcomeRejected, Code: fault.CodeNotAuthentic,
		AckedAtUnix: baseUnix + 30}, endpointKey())
	if err != nil {
		t.Fatal(err)
	}
	ackObject, err := relayframe.EncodeRoomAck(ack)
	if err != nil {
		t.Fatal(err)
	}
	add("room-ack", ackObject, nil)
	// A pending joiner refusing its Welcome holds no MLS state: no epoch
	// authenticator and MLS epoch 0.
	stateless, err := relayframe.SignRoomAck(relayframe.RoomAck{RoomID: vectorRoom, ObjectDigest: relayframe.ObjectDigest(welcome),
		RecipientEndpointID: delegation(t).EndpointID, RecipientDeviceID: deviceOne,
		Outcome: relayframe.OutcomeRejected, Code: fault.CodeNotAuthentic, AckedAtUnix: baseUnix + 31}, endpointKey())
	if err != nil {
		t.Fatal(err)
	}
	statelessObject, err := relayframe.EncodeRoomAck(stateless)
	if err != nil {
		t.Fatal(err)
	}
	add("room-ack-rejected-without-state", statelessObject, nil)
	aad, err := relayframe.EncodeRoomAAD(relayframe.RoomAAD{RoomID: vectorRoom, RoomEpoch: 2, MLSEpoch: 4,
		EpochAuthenticator: bytes.Repeat([]byte{0xa7}, 32), SenderAgentID: vectorAgent(1), EventID: "evt_" + strings.Repeat("1a", 32)})
	if err != nil {
		t.Fatal(err)
	}
	add("room-aad", aad, nil)

	// Split objects and reassembly sequences.
	sender, stranger := vectorAgent(0), vectorAgent(9)
	frameVector := func(from string, raw []byte, expected error) RoomFrameVector {
		vector := RoomFrameVector{Sender: from, Wire: hex.EncodeToString(raw), SHA256: canon.Digest(raw), Bytes: len(raw)}
		if expected != nil {
			vector.Error = expected.Error()
		}
		return vector
	}
	split := func(raw []byte, partBytes int) [][]byte {
		frames, err := relayframe.SplitRoomObject(raw, []byte(`{"card":"sender"}`), evidence, partBytes)
		if err != nil {
			t.Fatal(err)
		}
		return frames
	}
	reencode := func(raw []byte, change func(*relayframe.Frame)) []byte {
		frame, err := relayframe.Decode(raw)
		if err != nil {
			t.Fatal(err)
		}
		change(&frame)
		out, err := relayframe.Encode(frame)
		if err != nil {
			t.Fatal(err)
		}
		return out
	}
	sequence := func(name string, partBytes int, frames ...RoomFrameVector) {
		vectors = append(vectors, RoomVector{Name: name, PartBytes: partBytes, Members: []string{sender}, Frames: frames})
	}
	welcomeParts := split(welcome, vectorPartBytes)
	var inOrder []RoomFrameVector
	for _, raw := range welcomeParts {
		inOrder = append(inOrder, frameVector(sender, raw, nil))
	}
	sequence("room-split-welcome-test-cut", vectorPartBytes, inOrder...)

	// The largest valid object under the production cut, by recipe.
	maximal, err := relayframe.SplitRoomObject(maximalObject(t), nil, evidence, 0)
	if err != nil {
		t.Fatal(err)
	}
	var maximalFrames []RoomFrameVector
	for _, raw := range maximal {
		maximalFrames = append(maximalFrames, RoomFrameVector{Sender: sender, SHA256: canon.Digest(raw), Bytes: len(raw)})
	}
	vectors = append(vectors, RoomVector{Name: "room-split-maximal-production-cut", Recipe: maximalRecipe, Members: []string{sender}, Frames: maximalFrames})

	// Each reassembly refusal of section 4.
	sequence("room-reassembly-non-member", vectorPartBytes, frameVector(stranger, welcomeParts[1], relayframe.ErrReassemblyNotAdmitted))
	sequence("room-reassembly-inconsistent-part-count", vectorPartBytes,
		frameVector(sender, welcomeParts[0], nil),
		frameVector(sender, reencode(welcomeParts[1], func(f *relayframe.Frame) { f.PartCount++ }), relayframe.ErrReassemblyInconsistent))
	sequence("room-reassembly-repeated-index-other-bytes", vectorPartBytes,
		frameVector(sender, welcomeParts[1], nil),
		frameVector(sender, reencode(welcomeParts[1], func(f *relayframe.Frame) { f.Part = append([]byte(nil), f.Part...); f.Part[0] ^= 1 }), relayframe.ErrReassemblyInconsistent))
	last := len(welcomeParts) - 1
	digestFrames := []RoomFrameVector{}
	for index, raw := range welcomeParts {
		if index == last {
			raw = reencode(raw, func(f *relayframe.Frame) { f.Part = append([]byte(nil), f.Part...); f.Part[len(f.Part)-1] ^= 1 })
			digestFrames = append(digestFrames, frameVector(sender, raw, relayframe.ErrReassemblyDigest))
			continue
		}
		digestFrames = append(digestFrames, frameVector(sender, raw, nil))
	}
	sequence("room-reassembly-digest-mismatch", vectorPartBytes, digestFrames...)
	sequence("room-reassembly-object-over-bound", 0,
		frameVector(sender, reencode(welcomeParts[1], func(f *relayframe.Frame) { f.PartCount = 7 }), relayframe.ErrReassemblyObjectTooLarge))
	sequence("room-reassembly-not-the-fixed-cut", vectorPartBytes,
		frameVector(sender, reencode(welcomeParts[1], func(f *relayframe.Frame) { f.Part = f.Part[:len(f.Part)-1] }), relayframe.ErrReassemblyCut))
	sequence("room-reassembly-split-application", vectorPartBytes,
		frameVector(sender, reencode(welcomeParts[0], func(f *relayframe.Frame) {
			f.Part = append([]byte(nil), f.Part...)
			f.Part[len(canon.DomainRelayRoomObject)] = relayframe.RoomApplication
		}), relayframe.ErrReassemblyInconsistent))
	var perPeer []RoomFrameVector
	for index := 0; index < 5; index++ {
		other := object(relayframe.RoomObject{Type: relayframe.RoomWelcome, RoomID: vectorRoom, RoomEpoch: 2, MLSEpoch: 4, Header: header, Body: bytes.Repeat([]byte{byte('0' + index)}, 3_000)})
		var expected error
		if index == 4 {
			expected = relayframe.ErrReassemblyPeerObjects
		}
		perPeer = append(perPeer, frameVector(sender, split(other, vectorPartBytes)[1], expected))
	}
	sequence("room-reassembly-per-peer-objects", vectorPartBytes, perPeer...)
	// The digest every frame of one object carries is the whole object's.
	if decoded, err := relayframe.Decode(welcomeParts[1]); err != nil || decoded.ObjectDigest != sha256.Sum256(append([]byte(canon.DomainRelayObject), welcome...)) {
		t.Fatal(errors.New("a part does not carry the object digest"))
	}
	return vectors
}
